#!/usr/bin/env python3
"""Generates game/content/ui/credits.json from docs/ASSET_LICENSES.md (DEVELOPMENT_PLAN Step 15
scope 8, AC-15.5): every row of the third-party table becomes a credits entry (what, author,
license, source), plus the per-step "no third-party assets" notes as the in-house section.
Run from the repo root: python3 tools/gen_credits.py  (tools/check.sh verifies it is current)."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "ASSET_LICENSES.md"
OUT = ROOT / "game" / "content" / "ui" / "credits.json"


def strip_md(s: str) -> str:
    s = re.sub(r"`([^`]*)`", r"\1", s)
    s = re.sub(r"\*\*?([^*]*)\*\*?", r"\1", s)
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
    return s.strip()


def parse() -> dict:
    rows = []
    in_table = False
    for line in SRC.read_text(encoding="utf-8").splitlines():
        if line.startswith("| Path"):
            in_table = True
            continue
        if in_table and line.startswith("|---"):
            continue
        if in_table and line.startswith("|"):
            cells = [strip_md(c) for c in line.strip().strip("|").split("|")]
            if len(cells) >= 5:
                rows.append(
                    {"path": cells[0], "what": cells[1], "source": cells[2], "author": cells[3], "license": cells[4]}
                )
            continue
        in_table = False
    return {
        "game": [
            ["Project Lazarus — Vesper Peak", ""],
            ["Design, code, models, animation, audio synthesis, writing", "The Project Lazarus team"],
            ["Built with", "Godot Engine 4 (MIT)"],
        ],
        "third_party": rows,
        "in_house": "All other models, animations, textures, shaders, music, sound effects and voice are original "
        "works generated by the project's own tools and code (see ASSET_LICENSES.md).",
    }


def main() -> int:
    data = parse()
    text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("credits.json is stale: run python3 tools/gen_credits.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"credits.json: {len(data['third_party'])} third-party entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
