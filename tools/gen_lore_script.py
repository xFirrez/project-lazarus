#!/usr/bin/env python3
"""Generates maps/<map>/lore/script.md (human-readable VO script + document texts) from lore.json.

Usage: python3 tools/gen_lore_script.py [map_id]   (default vesper_peak; run from the repo root)
The JSON is the runtime source (LoreLibrary); edit it, then re-run this to refresh the script.
"""
import json
import sys
from pathlib import Path

map_id = sys.argv[1] if len(sys.argv) > 1 else "vesper_peak"
root = Path(__file__).resolve().parent.parent / "game" / "maps" / map_id / "lore"
data = json.loads((root / "lore.json").read_text())
spk = data["speakers"]
out = [f"# {map_id} — lore & VO script", "", "> Generated by `tools/gen_lore_script.py` from `lore.json` — do not edit by hand.", ""]
sections = [("doc", "Documents"), ("clue", "Clues"), ("reel", "Audio reels"), ("story", "Story entries"), ("vo", "Quest voice-over")]
for kind, title in sections:
    out += [f"## {title}", ""]
    for e in data["entries"]:
        if e["kind"] != kind:
            continue
        head = e["id"] + (f" — {e['title']}" if e.get("title") else "")
        out += [f"### {head}", f"*{e.get('zone', '')}*", ""]
        if "body" in e:
            out += ["> " + line if line else ">" for line in e["body"].split("\n")]
            out.append("")
        for line in e.get("lines", []):
            out.append(f"- **{spk.get(line[0], {}).get('name', line[0])}:** {line[1]}")
        out.append("")
(root / "script.md").write_text("\n".join(out))
print(f"wrote {root / 'script.md'}")
